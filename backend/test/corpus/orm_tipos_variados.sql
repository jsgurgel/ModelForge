CREATE TABLE Tipos_Variados (
    a integer,
    b bigint NOT NULL,
    c smallint,
    d double precision,
    e float,
    f real NOT NULL,
    g boolean,
    h date,
    i timestamp,
    j timestamptz,
    k time,
    l uuid,
    m char(3),
    n nchar(5) NOT NULL,
    o text,
    p numeric(8,3),
    q numeric,
    r jsonb,
    s bytea,
    t varchar,
    u bigserial,
    v decimal(5,2) DEFAULT 0 NOT NULL,
    w varchar(30) DEFAULT 'x' UNIQUE
);
